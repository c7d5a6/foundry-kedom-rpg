func localeOrEN(locale string) string {
	if locale == "" {
		return "en"
	}
	return locale
}

func writeProse(b *strings.Builder, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		b.WriteString("_(no description yet)_\n")
		return
	}
	b.WriteString(text)
	if !strings.HasSuffix(text, "\n") {
		b.WriteString("\n")
	}
}

func flattenProse(text string) string {
	return strings.Join(strings.Fields(strings.TrimSpace(text)), " ")
}
